#Requires -Version 5.1
<#
Derive service-level .env blocks from the root .env.

Why: Agent uses AUTH__JWT_KID / LLM__API_KEY while the root file uses JWT_KID /
LLM_API_KEY, so hand-copying always drifts (for example CONTROL_PLANE__BASE_URL
keeps pointing at an old port after the port is changed). Everything outside the
managed block is preserved, so service-private tuning remains editable.

Usage:
  pwsh -File scripts/config/generate-config.ps1          # generate and write
  pwsh -File scripts/config/generate-config.ps1 -Check   # compare only, exit 1 when stale

ASCII-only on purpose: Windows PowerShell 5.1 reads BOM-less scripts as ANSI and
would mangle non-ASCII literals.
#>

[CmdletBinding()]
param(
    [string]$RepoRoot,
    [switch]$Check
)

$ErrorActionPreference = 'Stop'

# $PSScriptRoot is not reliable inside param defaults on Windows PowerShell 5.1
if ([string]::IsNullOrWhiteSpace($RepoRoot)) {
    $RepoRoot = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
}

$blockStart = '# >>> generated by scripts/config/generate-config.ps1 from root .env - do not edit >>>'
$blockEnd = '# <<< end of generated block <<<'

function Read-DotEnv {
    param([string]$Path)

    $map = @{}
    if (-not (Test-Path -LiteralPath $Path)) { return $map }
    foreach ($line in Get-Content -LiteralPath $Path -Encoding UTF8) {
        if ($line -match '^\s*#' -or $line -match '^\s*$') { continue }
        if ($line -match '^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=(.*)$') {
            $value = $matches[2].Trim()
            if ($value.Length -ge 2 -and $value.StartsWith('"') -and $value.EndsWith('"')) {
                $value = $value.Substring(1, $value.Length - 2)
            }
            $map[$matches[1]] = $value
        }
    }
    return $map
}

# Templates may only reference keys that exist in the root .env: a typo must fail
# here instead of silently producing a half-built URL.
function Expand-Template {
    param([string]$Template, [hashtable]$Values)

    return [regex]::Replace($Template, '\{([A-Za-z_][A-Za-z0-9_]*)\}', {
        param($match)
        $key = $match.Groups[1].Value
        if (-not $Values.ContainsKey($key)) {
            throw "Derivation template references a key missing from root .env: $key"
        }
        return $Values[$key]
    })
}

$schemaPath = Join-Path $RepoRoot 'config/env.schema.json'
if (-not (Test-Path -LiteralPath $schemaPath)) {
    Write-Host "FAIL: missing config contract $schemaPath" -ForegroundColor Red
    exit 1
}
$schema = Get-Content -LiteralPath $schemaPath -Raw -Encoding UTF8 | ConvertFrom-Json

$rootPath = Join-Path $RepoRoot $schema.files.root
$root = Read-DotEnv -Path $rootPath
if ($root.Count -eq 0) {
    Write-Host "FAIL: root $($schema.files.root) not found, copy .env.example first" -ForegroundColor Red
    exit 1
}

$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
$staleFiles = New-Object System.Collections.Generic.List[string]
$writtenFiles = New-Object System.Collections.Generic.List[string]

foreach ($target in $schema.derived.PSObject.Properties) {
    $alias = $target.Name
    $relativePath = $schema.files.$alias
    if ([string]::IsNullOrWhiteSpace($relativePath)) {
        throw "Config contract is missing files.$alias"
    }

    $entries = @($target.Value)
    $managedKeys = @($entries | ForEach-Object { $_.key })
    $blockLines = New-Object System.Collections.Generic.List[string]
    $blockLines.Add($blockStart)

    foreach ($entry in $entries) {
        $value = $null
        if ($entry.PSObject.Properties.Name -contains 'from') {
            if (-not $root.ContainsKey($entry.from)) {
                throw "Root .env is missing $($entry.from), cannot derive $alias / $($entry.key)"
            }
            $value = $root[$entry.from]
        } elseif ($entry.PSObject.Properties.Name -contains 'template') {
            $value = Expand-Template -Template $entry.template -Values $root
        } elseif ($entry.PSObject.Properties.Name -contains 'const') {
            $value = [string]$entry.const
        } else {
            throw "Derived entry $($entry.key) must declare from / template / const"
        }
        $blockLines.Add("$($entry.key)=$value")
    }
    $blockLines.Add($blockEnd)

    $targetPath = Join-Path $RepoRoot $relativePath
    $existing = ''
    if (Test-Path -LiteralPath $targetPath) {
        $existing = [System.IO.File]::ReadAllText($targetPath, [System.Text.Encoding]::UTF8)
    }
    $existing = $existing.TrimStart([char]0xFEFF)

    # Keep private settings outside the managed block. Managed keys are removed
    # wherever they appear so the file has exactly one definition per key.
    $managedPattern = '^\s*(' + (($managedKeys | ForEach-Object { [regex]::Escape($_) }) -join '|') + ')\s*='
    $kept = New-Object System.Collections.Generic.List[string]
    foreach ($line in ($existing -split "`r?`n")) {
        if ($line -eq $blockStart -or $line -eq $blockEnd) { continue }
        if ($line -match $managedPattern) { continue }
        $kept.Add($line)
    }
    while ($kept.Count -gt 0 -and [string]::IsNullOrWhiteSpace($kept[$kept.Count - 1])) {
        $kept.RemoveAt($kept.Count - 1)
    }

    $newContent = (($kept -join "`n") + "`n`n" + ($blockLines -join "`n") + "`n")

    if ($Check) {
        $normalizedExisting = ($existing -replace "`r`n", "`n").TrimEnd()
        $normalizedNew = $newContent.TrimEnd()
        if ($normalizedExisting -ne $normalizedNew) {
            $staleFiles.Add($relativePath)
            Write-Host "  [STALE] $relativePath - run scripts/config/generate-config.ps1" -ForegroundColor Yellow
        } else {
            Write-Host "  [PASS] $relativePath matches root .env" -ForegroundColor Green
        }
        continue
    }

    # Atomic replace: write a temp file in the same directory first so a failure
    # never leaves a truncated .env behind.
    $directory = Split-Path -Parent $targetPath
    if (-not (Test-Path -LiteralPath $directory)) {
        New-Item -ItemType Directory -Path $directory -Force | Out-Null
    }
    $tempPath = Join-Path $directory ('.' + (Split-Path -Leaf $targetPath) + '.tmp')
    [System.IO.File]::WriteAllText($tempPath, $newContent, $utf8NoBom)
    if (Test-Path -LiteralPath $targetPath) {
        # [NullString]::Value avoids PowerShell binding $null as an empty backup path
        [System.IO.File]::Replace($tempPath, $targetPath, [NullString]::Value)
    } else {
        [System.IO.File]::Move($tempPath, $targetPath)
    }
    $writtenFiles.Add($relativePath)
    Write-Host "  [WRITE] $relativePath" -ForegroundColor Cyan
}

if ($Check) {
    if ($staleFiles.Count -gt 0) {
        Write-Host ("Stale derived config: {0} file(s)" -f $staleFiles.Count) -ForegroundColor Red
        exit 1
    }
    Write-Host 'Derived config is up to date.' -ForegroundColor Green
    exit 0
}

Write-Host ("Derived config written: {0} file(s). Restart Agent / Vite to apply." -f $writtenFiles.Count) -ForegroundColor Green
exit 0
